#!/usr/bin/env bash
set -euo pipefail

# Generate a §15 secrets.env for the ios-release job.
#
#   ./ci/ios/write-secrets-env.sh [config-dir]      # default ~/.latem
#
# Run it yourself on the runner. It prompts for the two passwords and reads the
# .p8 from disk, so no credential is typed into a chat, pasted into a
# transcript, or left in shell history.
#
# WHY A SCRIPT AND NOT INSTRUCTIONS
#
# APP_STORE_CONNECT_KEY_P8 is a multi-line PEM and §15's file format needs it on
# ONE line, double-quoted, with \n escapes. Only \n \r \t \\ and \" are legal
# escapes there — an unknown one is a parse error, because the two readings of
# \n differ by an entire PEM. Hand-writing that is easy to get subtly wrong and
# the failure arrives much later as an authentication error mentioning nothing
# about quoting.
#
# It also derives APP_STORE_CONNECT_KEY_ID from the .p8 filename rather than
# asking for it. Apple names every download AuthKey_<KEY_ID>.p8, and typing the
# id separately is how a JWT ends up claiming one key while being signed by
# another — which Apple rejects with a 401 that names neither half.
#
# Verified 2026-08-11: output round-trips through latem's own parser with the
# PEM intact and a password containing quotes, backslashes and a tab.

CFG="${1:-$HOME/.latem}"
OUT="$CFG/secrets.env"

read -r -p "path to your AuthKey_*.p8: " P8
P8="${P8/#\~/$HOME}"
[ -f "$P8" ] || { echo "no such file: $P8" >&2; exit 1; }

# The key id is the filename Apple generated — the mismatch that cost an hour
# earlier today came from typing it separately, so derive it instead.
KEY_ID="$(basename "$P8" | sed -n 's/^AuthKey_\(.*\)\.p8$/\1/p')"
[ -n "$KEY_ID" ] || { echo "filename is not AuthKey_XXXXXXXXXX.p8; cannot derive the key id" >&2; exit 1; }
echo "  key id (from filename): $KEY_ID"

read -r -p "App Store Connect issuer id (UUID): " ISSUER_ID
read -r -p "match git url [https://github.com/Abyssinia-Labs/latem-certificates.git]: " MATCH_URL
MATCH_URL="${MATCH_URL:-https://github.com/Abyssinia-Labs/latem-certificates.git}"

read -r -s -p "MATCH_PASSWORD (the match passphrase): " MATCH_PW; echo
read -r -s -p "KEYCHAIN_PASSWORD (your macOS login password): " KC_PW; echo

umask 077
KEY_ID="$KEY_ID" ISSUER_ID="$ISSUER_ID" MATCH_URL="$MATCH_URL" \
MATCH_PW="$MATCH_PW" KC_PW="$KC_PW" P8="$P8" \
python3 - "$OUT" <<'PY'
import os, sys

def dq(s: str) -> str:
    """Double-quoted §15 value. Only \\n \\r \\t \\\\ \\" are legal escapes —
    an unknown one is a parse error rather than a literal backslash, because
    the two readings of \\n differ by an entire PEM."""
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\r", "\\r").replace("\t", "\\t").replace("\n", "\\n")
    return '"' + out + '"'

pem = open(os.environ["P8"]).read().rstrip("\n")

lines = [
    "# §15 secrets for ios-release. Mode 0600; never committed.",
    "# Generated by write-secrets.sh — values were read from disk and prompts,",
    "# not from a transcript.",
    "",
    f'APP_STORE_CONNECT_KEY_ID={os.environ["KEY_ID"]}',
    f'APP_STORE_CONNECT_ISSUER_ID={os.environ["ISSUER_ID"]}',
    f'MATCH_GIT_URL={os.environ["MATCH_URL"]}',
    f'MATCH_PASSWORD={dq(os.environ["MATCH_PW"])}',
    f'KEYCHAIN_PASSWORD={dq(os.environ["KC_PW"])}',
    f'APP_STORE_CONNECT_KEY_P8={dq(pem)}',
    "",
]
open(sys.argv[1], "w").write("\n".join(lines))
PY

chmod 600 "$OUT"
echo
echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines, mode $(stat -f '%Lp' "$OUT"))"
echo "names only:"
grep -oE '^[A-Z_]+=' "$OUT" | tr -d '=' | sed 's/^/  /'
