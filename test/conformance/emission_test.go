func seed(t *testing.T, db *store.DB, id string, state protocol.RunState) {
	t.Helper()
	if err := db.Create(context.Background(), store.Run{
		ID: id, Repo: "myapp", Job: "ios-beta", Ref: "main",
		State: state, OriginKind: "cli", CreatedAt: time.Now(),
	}); err != nil {
		t.Fatal(err)
	}
}

func waitFor(t *testing.T, why string, timeout time.Duration, cond func() bool) {
	t.Helper()
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		if cond() {
			return
		}
		time.Sleep(5 * time.Millisecond)
	}
	t.Fatalf("timed out after %s waiting for %s", timeout, why)
}
