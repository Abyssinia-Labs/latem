package conformance

// What the agent puts on the wire, pinned.
//
// Every frame internal/broker/remote emits is driven here through the public
// broker.Broker surface, recorded verbatim off a real WebSocket, canonicalised,
// and compared against testdata/agent-frames.jsonl. A field renamed, a field
// that stops being omitempty, a payload that moves a level, a version stamp
// that goes missing — each of those is a diff in a committed file rather than
// a decode error in somebody else's repository three weeks later.

import (
	"context"
	"encoding/json"
	"strings"
	"testing"
	"time"

	"github.com/Abyssinia-Labs/latem/internal/broker/remote"
	"github.com/Abyssinia-Labs/latem/internal/store"
	"github.com/Abyssinia-Labs/latem/pkg/protocol"
)

const agentCorpus = "agent-frames.jsonl"

const agentCorpusHeader = `// Frames this agent emits, canonicalised: object keys sorted, the envelope's
// per-session correlation id replaced with __correlation_id__, and every
// RFC 3339 timestamp replaced with __rfc3339__. See docs/PROTOCOL.md §4.
//
// Generated by test/conformance. Regenerate with:
//     go test ./test/conformance -update
// Do not hand-edit: a diff here is a wire change, and a wire change that is
// correct still has to be a deliberate commit.
`

// TestConformance_AgentEmissions drives every agent-to-server frame kind and
// compares what reached the socket with the committed corpus.
func TestConformance_AgentEmissions(t *testing.T) {
	dir := shortTemp(t)
	db := openStore(t, dir)
	rec := newRecorder(t, "tok-conformance")
	// A61, A68: a control plane that says 2.4 is sent a plan's requires,
	// runs_on and reads_vars, and a heartbeat's toolchains and label_aliases.
	rec.hello = []byte(`{"kind":"hello","hello":{"protocol_version":"` + protocol.Version + `"}}`)

	ctx := context.Background()

	// A non-terminal run, so the resume frame carries a run rather than the
	// `"runs": null` an empty machine sends. Both shapes are in the corpus:
	// the null one is what every machine sends on its very first connection
	// and is docs/PROTOCOL.md §5.1's first trap.
	seed(t, db, "r-alpha", protocol.StateRunning)
	seed(t, db, "r-beta", protocol.StateQueued)

	// A non-zero resume point, so the corpus carries a uint64 on the wire
	// somewhere other than a log sequence. docs/PROTOCOL.md §5.8 records that
	// every JavaScript control plane parses these as doubles; a corpus that
	// only ever showed zero would let that go unnoticed for one more release.
	if err := db.SetLastAckedSeq(ctx, store.BrokerRemote, "r-alpha", 4200); err != nil {
		t.Fatal(err)
	}

	b, err := remote.Open(remote.Options{
		URL:            rec.URL(),
		TokenFile:      writeTokenFile(t, dir, "tok-conformance"),
		MachineID:      "mac-mini-01",
		Store:          db,
		QueueTTL:       72 * time.Hour,
		LogMode:        remote.LogsAlways,
		RequestTimeout: 20 * time.Second,
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = b.Close() })

	commands, err := b.Commands(ctx)
	if err != nil {
		t.Fatal(err)
	}

	// --- resume (§4.1) ------------------------------------------------------
	rec.waitForKind(t, "resume", 20*time.Second)
	deadline := time.Now().Add(20 * time.Second)
	for !b.SpeaksRequires() {
		if time.Now().After(deadline) {
			t.Fatal("the broker never read the hello")
		}
		time.Sleep(10 * time.Millisecond)
	}

	// --- heartbeat (§4.5) ---------------------------------------------------
	if err := b.Heartbeat(ctx, protocol.MachineHealth{
		MachineID: "mac-mini-01", AgentVer: "0.4.1", OS: "darwin", Arch: "arm64",
		Runners: []protocol.RunnerInfo{{
			Name: "ios", Executor: "tart", Labels: []string{"ios", "macos"},
			Concurrency: 1, Active: 1, Available: true,
		}, {
			Name: "linux", Executor: "docker", Concurrency: 4, Active: 0,
			Available: false, Unavailable: "the docker daemon is not answering",
		}},
		DiskFreeGB: 412.5,
		// A52: how an installation's repository finds its machines. A
		// repository not on GitHub has a key and no slug.
		Repos: []protocol.RepoInfo{
			{Key: "myapp", GitHub: "Abyssinia-Labs/myapp", Vars: map[string]string{"LATEM": "b5bea41b6c623f7c"}},
			{Key: "scratch"},
		},
		LabelAliases: map[string][]string{"blacksmith-6vcpu-macos-26": {"macos"}},
		// A61: versions and names, never a path.
		Toolchains: &protocol.Toolchains{
			Xcode: []string{"26.0.1", "27.0"}, IOSSimulator: true, JDK: []int{17, 21},
			AndroidSDK: true, AndroidPlatforms: []int{35, 36}, AndroidEmulator: true,
			Tools: []string{"bun", "docker", "xcodegen"},
		},
		// A63: the machine's size and each runner's recommended concurrency.
		Capacity: &protocol.Capacity{
			CPUs: 8, MemoryGB: 16, Docker: &protocol.DockerCapacity{CPUs: 6, MemoryGB: 7.7},
			Runners: []protocol.RunnerCapacity{
				{Name: "ios", Recommended: 1, Why: "this Mac has 16 GB: a macOS VM takes about 8 GB and the host keeps 8, and Apple's licence allows 2 VMs"},
				{Name: "linux", Recommended: 1, Why: "Docker has 6 CPUs and 7.7 GB, and a job takes about 2 CPUs and 4 GB"},
			},
		},
	}); err != nil {
		t.Fatalf("heartbeat: %v", err)
	}
	rec.waitForKind(t, "heartbeat", 20*time.Second)

	// The second documented null (§5.2): a machine whose runners slice is nil
	// writes `"runners": null`, not `[]`. A reader that assumed an array
	// crashes on the first machine whose preflight has not run yet.
	if err := b.Heartbeat(ctx, protocol.MachineHealth{
		MachineID: "mac-mini-01", AgentVer: "0.4.1", OS: "linux", Arch: "amd64",
		DiskFreeGB: 0, Draining: true,
	}); err != nil {
		t.Fatalf("heartbeat: %v", err)
	}

	// --- claim (§4.6) -------------------------------------------------------
	if err := b.Claim(ctx, "r-alpha"); err != nil {
		t.Fatalf("claim: %v", err)
	}

	// --- update (§4.2), twice: a minimal one and a maximal one --------------
	if err := b.Report(ctx, "r-alpha", protocol.Update{State: protocol.StateRunning}); err != nil {
		t.Fatalf("report: %v", err)
	}

	at := time.Date(2026, 8, 8, 9, 15, 0, 0, time.UTC)
	fin := at.Add(11 * time.Minute)
	exit := 0
	expires := at.Add(24 * time.Hour)
	if err := b.Report(ctx, "r-alpha", protocol.Update{
		State:      protocol.StateSucceeded,
		ExitCode:   &exit,
		StartedAt:  &at,
		FinishedAt: &fin,
		Artifacts: []protocol.ArtifactRef{
			{Path: "build/app.ipa", SizeBytes: 84233216, SHA256: strings.Repeat("9f", 32)},
			{Path: "build/app.aab", SizeBytes: 42116608, SHA256: strings.Repeat("1c", 32),
				ExpiresAt: &expires},
		},
		Runner:        "ios",
		ExpiresAt:     &expires,
		CancelReason:  "wrong branch",
		RefNormalized: "refs/heads/main",
		SHA:           "3bf12613f4a2a8f9d24a5e0c1b7d9e3a5c8f0b21",
		ErrorCode:     protocol.ErrStep,
		ErrorMsg:      "step 2 exited 1",
		Outputs:       map[string]string{"version": "1.4.0", "changed-web": "true"},
	}); err != nil {
		t.Fatalf("report: %v", err)
	}

	// --- plan (A52), twice: a plan and a refusal to make one ----------------
	if err := b.ReportPlan(ctx, protocol.PlanResult{
		ID: "p-alpha",
		Workflows: []protocol.PlannedWorkflow{{
			File: ".github/workflows/checks.yml", Name: "Checks", RunName: "Checks on main",
			Concurrency: &protocol.Concurrency{Group: "checks-refs/heads/main", CancelInProgress: true},
			Jobs: []protocol.PlannedJob{{
				Key: "lint", Name: "lint", Labels: []string{"linux"},
				Permissions: map[string]string{"contents": "read"}, TimeoutMinutes: 360,
				// A61: what it needs that nothing in it provides.
				Requires: []protocol.Requirement{{Key: "xcode", Version: "27"}, {Key: "ios-simulator"}},
				RunsOn: []protocol.RunsOnLabel{
					{Label: "macos-latest", Hosted: []string{"macos"}},
					{Label: "blacksmith-6vcpu-macos-26"},
				},
				ReadsVars: []string{"LATEM"},
			}, {
				Key: "web", Name: "Web build", Needs: []string{"lint"}, Labels: []string{"linux"},
				Environment: "staging", Permissions: map[string]string{},
				Concurrency:    &protocol.Concurrency{Group: "deploy-staging"},
				IfChecksStatus: true, ContinueOnError: true, TimeoutMinutes: 30,
			}, {
				// A55: a matrix job's legs, each with its values and its place.
				Key: "check", Name: "check (linux, 22)", Labels: []string{"linux"},
				Permissions: map[string]string{"contents": "read"}, TimeoutMinutes: 360,
				Matrix:   json.RawMessage(`{"node":22,"os":"linux"}`),
				Strategy: &protocol.Strategy{JobIndex: 0, JobTotal: 2, FailFast: true},
			}, {
				Key: "check", Name: "check (macos, 22)", Labels: []string{"macos"},
				Permissions: map[string]string{"contents": "read"}, TimeoutMinutes: 360,
				Matrix:   json.RawMessage(`{"node":22,"os":"macos"}`),
				Strategy: &protocol.Strategy{JobIndex: 1, JobTotal: 2, FailFast: true, MaxParallel: 1},
			}, {
				Key: "called", Name: "called", Permissions: map[string]string{"contents": "read"},
				TimeoutMinutes: 360, Error: "uses: calls the reusable workflow ./.github/workflows/r.yml, and " +
					"reusable workflows are not planned yet (A52)",
			}},
		}, {
			File: ".github/workflows/deploy-production.yml", Name: "Deploy production",
			Inputs: map[string]string{"ref": "v1.2.3", "dry": "false"},
		}, {
			File: ".github/workflows/broken.yml", Name: ".github/workflows/broken.yml",
			Error: "parsing .github/workflows/broken.yml: unknown field \"stepz\"",
		}},
	}); err != nil {
		t.Fatalf("plan: %v", err)
	}
	// The second documented null: a plan that triggers nothing writes
	// `"workflows": []`, and one that could not be made writes null — both are
	// in the corpus because a reader that assumed an array crashes on the second.
	if err := b.ReportPlan(ctx, protocol.PlanResult{
		ID: "p-beta", ErrorCode: protocol.ErrSource, Error: "fetching myapp: exit status 128",
	}); err != nil {
		t.Fatalf("plan: %v", err)
	}
	if err := b.ReportPlan(ctx, protocol.PlanResult{ID: "p-gamma", Workflows: []protocol.PlannedWorkflow{}}); err != nil {
		t.Fatalf("plan: %v", err)
	}

	// --- logs (§4.3) --------------------------------------------------------
	sink, err := b.Logs(ctx, "r-alpha")
	if err != nil {
		t.Fatalf("logs: %v", err)
	}
	// The sequences start above the resume point set above. A batch at or
	// below it is dropped as already delivered, which is correct behaviour and
	// silently produces no frame at all — the coverage assertion at the bottom
	// of this test is what caught it being written the other way round.
	logAt := time.Date(2026, 8, 8, 9, 15, 3, 500000000, time.UTC)
	if err := sink.Write(ctx, []protocol.LogFrame{
		{RunID: "r-alpha", Seq: 4201, Stream: protocol.StreamAgent, At: logAt, Line: "[latem] preparing"},
		{RunID: "r-alpha", Seq: 4202, Stream: protocol.StreamStdout, At: logAt, Line: "> build"},
		{RunID: "r-alpha", Seq: 4203, Stream: protocol.StreamStderr, At: logAt, Line: "warning: none"},
	}); err != nil {
		t.Fatalf("writing logs: %v", err)
	}
	waitFor(t, "the log batch to be acknowledged", 20*time.Second, func() bool {
		return sink.Acked() >= 4203
	})
	if err := sink.Close(ctx); err != nil {
		t.Fatalf("closing the sink: %v", err)
	}

	// --- ack, agent → server (§4.7) -----------------------------------------
	//
	// The agent only produces one in answer to a command, so a command has to
	// be sent. It is the last thing driven because it puts a run in the store.
	rec.push(t, []byte(`{"kind":"command","id":"j57abc","protocol_version":"1.0","command":{`+
		`"kind":"run","run":{"id":"r7k9m2p4","repo":"myapp","job":"ios-beta","ref":"main",`+
		`"inputs":{"lane":"beta"},"origin":{"kind":"manual","actor":"michael@example.com",`+
		`"requested_at":"2026-08-08T09:15:00.000Z"}}}}`))
	select {
	case <-commands:
	case <-time.After(20 * time.Second):
		t.Fatal("the agent never yielded the command it was sent")
	}
	rec.waitForKind(t, "ack", 20*time.Second)

	// --- the second resume shape: a machine with nothing in flight ----------
	//
	// docs/PROTOCOL.md §5.1: protocol.Resume.Runs has no omitempty, so Go
	// writes a nil slice as `"runs": null`, and that is what every machine
	// sends on its very first connection. A reader that assumed an array
	// crashes there, so the shape belongs in the corpus rather than in a
	// sentence.
	emptyDir := shortTemp(t)
	emptyRec := newRecorder(t, "")
	empty, err := remote.Open(remote.Options{
		URL:       emptyRec.URL(),
		TokenFile: writeTokenFile(t, emptyDir, "tok-empty"),
		Store:     openStore(t, emptyDir),
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = empty.Close() })
	if _, err := empty.Commands(ctx); err != nil {
		t.Fatal(err)
	}
	emptyResume := emptyRec.waitForKind(t, "resume", 20*time.Second)

	// --- compare ------------------------------------------------------------
	var got []string
	for _, raw := range append(rec.frames(), emptyResume) {
		got = append(got, canonicalise(t, raw))
	}
	got = sortedUnique(got)

	if *update {
		writeCorpus(t, agentCorpus, got, agentCorpusHeader)
		return
	}

	want := readCorpus(t, agentCorpus)
	compareCorpus(t, want, got)
	assertEveryAgentKindIsCovered(t, got)
}

// compareCorpus reports the difference in both directions.
//
// Both halves matter. A frame that appeared is a wire change nobody committed;
// a frame that disappeared is a kind this test stopped exercising, which is how
// a corpus rots into a file that pins three of eight frame shapes and passes.
func compareCorpus(t *testing.T, want, got []string) {
	t.Helper()

	inWant := map[string]bool{}
	for _, w := range want {
		inWant[w] = true
	}
	inGot := map[string]bool{}
	for _, g := range got {
		inGot[g] = true
	}

	for _, g := range got {
		if !inWant[g] {
			t.Errorf("the agent emitted a frame the corpus does not contain:\n  %s\n"+
				"if this is a deliberate wire change, regenerate with "+
				"`go test ./test/conformance -update` and commit the diff", g)
		}
	}
	for _, w := range want {
		if !inGot[w] {
			t.Errorf("the corpus contains a frame the agent no longer emits:\n  %s", w)
		}
	}
}

// agentKinds is docs/PROTOCOL.md §2.4's agent-to-server half.
var agentKinds = []string{"resume", "update", "logs", "heartbeat", "claim", "ack", "plan"}

// assertEveryAgentKindIsCovered stops the corpus from silently shrinking.
//
// A golden-file test that compares a set against a set is exactly as good as
// the set it was given: delete the heartbeat call above and both sides agree
// on five kinds, forever. The eight kinds are named in the protocol document,
// so they are named here too.
func assertEveryAgentKindIsCovered(t *testing.T, got []string) {
	t.Helper()
	seen := map[string]int{}
	for _, line := range got {
		var env struct {
			Kind    string `json:"kind"`
			Version string `json:"protocol_version"`
		}
		if err := json.Unmarshal([]byte(line), &env); err != nil {
			t.Fatalf("the corpus contains a line that is not JSON: %s", line)
		}
		seen[env.Kind]++
		// §2.2: encode stamps the version on every frame in both directions.
		if env.Version != protocol.Version {
			t.Errorf("a %s frame carries protocol_version %q, want %q:\n  %s",
				env.Kind, env.Version, protocol.Version, line)
		}
	}
	for _, k := range agentKinds {
		if seen[k] == 0 {
			t.Errorf("the corpus covers no %q frame; docs/PROTOCOL.md §2.4 lists seven kinds the "+
				"agent emits and this test must drive all of them", k)
		}
	}
}

// TestConformance_EnvelopeIDsMatchTheDocumentedTable pins §2.1.
//
// Which frames carry a correlation id is not cosmetic: a frame with no id gets
// no answer, because there is nothing to correlate a reply with. A server that
// acknowledges a resume is talking to nobody, and an agent that stopped putting
// an id on a log batch would wait out its request timeout on every batch and
// never advance a resume point.
func TestConformance_EnvelopeIDsMatchTheDocumentedTable(t *testing.T) {
	wantsID := map[string]bool{
		"resume":    false,
		"heartbeat": false,
		"claim":     true,
		"update":    true,
		"logs":      true,
		"ack":       true,
		"plan":      true,
	}

	for _, line := range readCorpus(t, agentCorpus) {
		var env map[string]any
		if err := json.Unmarshal([]byte(line), &env); err != nil {
			t.Fatalf("the corpus contains a line that is not JSON: %s", line)
		}
		kind, _ := env["kind"].(string)
		want, known := wantsID[kind]
		if !known {
			t.Errorf("the corpus contains a %q frame, which is not one the agent may send", kind)
			continue
		}
		_, has := env["id"]
		if has != want {
			t.Errorf("a %s frame %s a correlation id; docs/PROTOCOL.md §2.1 says it %s:\n  %s",
				kind, presence(has), presence(want), line)
		}
	}
}

func presence(b bool) string {
	if b {
		return "carries"
	}
	return "does not carry"
}

